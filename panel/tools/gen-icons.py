#!/usr/bin/env python3
"""Write panel/www/js/core/icons.gen.js from the vendored Ridgeline icons.

Every Phosphor SVG in ridgeline/<version>/icons/{light,regular} is one path in
a 256 x 256 box. The UI draws icons inline (so they inherit currentColor), and
reading them from a JS table keeps that synchronous. Run this after copying a
new Ridgeline version or adding an icon:

    python3 panel/tools/gen-icons.py
"""
import json
import re
import sys
from pathlib import Path

UI = Path(__file__).resolve().parent.parent / "www"
OUT = UI / "js" / "core" / "icons.gen.js"


def ridgeline_dir() -> Path:
    versions = sorted((UI / "ridgeline").iterdir(), key=lambda p: [int(x) for x in p.name.split(".")])
    return versions[-1]


def read_weight(icons: Path, weight: str) -> dict:
    table = {}
    for svg in sorted((icons / weight).glob("*.svg")):
        paths = re.findall(r'\bd="([^"]+)"', svg.read_text())
        if len(paths) != 1:
            sys.exit(f"{svg}: expected one path, found {len(paths)}")
        table[svg.stem] = paths[0]
    return table


def main() -> None:
    rl = ridgeline_dir()
    icons = rl / "icons"
    lines = [
        f"// Generated by panel/tools/gen-icons.py from ridgeline/{rl.name}/icons. Do not edit.",
        "// name -> SVG path data in a 256 x 256 box (Phosphor).",
    ]
    for weight in ("light", "regular"):
        table = read_weight(icons, weight)
        lines.append(f"export const {weight.upper()} = {json.dumps(table, indent=0, separators=(',', ':'))};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(UI.parent.parent)}")


if __name__ == "__main__":
    main()
